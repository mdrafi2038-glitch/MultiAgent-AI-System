import os
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path


def _database_url() -> str:
    return os.getenv("DATABASE_URL", "").strip()


def _is_postgres() -> bool:
    return bool(_database_url())


def _sql(statement: str) -> str:
    return statement if _is_postgres() else statement.replace("%s", "?")


@contextmanager
def connect():
    database_url = _database_url()
    if database_url:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("PostgreSQL support requires psycopg. Install requirements.txt.") from exc

        url = database_url
        if url.startswith("postgres://"):
            url = "postgresql://" + url[len("postgres://"):]
        db = psycopg.connect(
            url,
            row_factory=dict_row,
            connect_timeout=10,
            sslmode="require",
            application_name="multiagent-ai-system",
        )
    else:
        path = Path(os.getenv("APP_DB_PATH", "./data/multiagent.db"))
        path.parent.mkdir(parents=True, exist_ok=True)
        db = sqlite3.connect(path)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys = ON")

    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def init_db():
    with connect() as db:
        if _is_postgres():
            db.execute("""
                CREATE TABLE IF NOT EXISTS tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_message TEXT NOT NULL,
                    status TEXT NOT NULL,
                    result TEXT,
                    created_at TEXT NOT NULL
                )
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
                    agent TEXT NOT NULL,
                    content TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)
            db.execute("CREATE INDEX IF NOT EXISTS idx_messages_task_id ON messages(task_id)")
            db.execute("CREATE INDEX IF NOT EXISTS idx_tasks_created_at ON tasks(created_at)")
        else:
            db.executescript("""
                CREATE TABLE IF NOT EXISTS tasks (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_message TEXT NOT NULL,
                    status TEXT NOT NULL,
                    result TEXT,
                    created_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS messages (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
                    agent TEXT NOT NULL,
                    content TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS idx_messages_task_id ON messages(task_id);
                CREATE INDEX IF NOT EXISTS idx_tasks_created_at ON tasks(created_at);
            """)


def create_task(message: str) -> int:
    with connect() as db:
        cur = db.execute(
            _sql("INSERT INTO tasks(user_message,status,created_at) VALUES(%s,%s,%s)"),
            (message, "running", datetime.now(timezone.utc).isoformat()),
        )
        if _is_postgres():
            # PostgreSQL returns the generated identity value explicitly.
            row = db.execute("SELECT currval(pg_get_serial_sequence('tasks', 'id')) AS id").fetchone()
            return int(row["id"])
        return int(cur.lastrowid)


def add_message(task_id: int, agent: str, content: str):
    with connect() as db:
        db.execute(
            _sql("INSERT INTO messages(task_id,agent,content,created_at) VALUES(%s,%s,%s,%s)"),
            (task_id, agent, content, datetime.now(timezone.utc).isoformat()),
        )


def finish_task(task_id: int, status: str, result: str):
    with connect() as db:
        db.execute(
            _sql("UPDATE tasks SET status=%s, result=%s WHERE id=%s"),
            (status, result, task_id),
        )


def recent_tasks(limit: int = 30):
    with connect() as db:
        rows = db.execute(
            _sql("SELECT id,user_message,status,result,created_at FROM tasks ORDER BY id DESC LIMIT %s"),
            (limit,),
        ).fetchall()
        return [dict(row) for row in rows]


def task_messages(task_id: int):
    with connect() as db:
        rows = db.execute(
            _sql("SELECT agent,content,created_at FROM messages WHERE task_id=%s ORDER BY id"),
            (task_id,),
        ).fetchall()
        return [dict(row) for row in rows]
