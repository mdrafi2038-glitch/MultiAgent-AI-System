import os
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path


def _database_url() -> str:
    return os.getenv("DATABASE_URL", "").strip()


def _is_postgres() -> bool:
    return bool(_database_url())


def _sql(statement: str) -> str:
    return statement if _is_postgres() else statement.replace("%s", "?")


@contextmanager
def connect():
    database_url = _database_url()
    if database_url:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("PostgreSQL support requires psycopg. Install requirements.txt.") from exc
        url = database_url
        if url.startswith("postgres://"):
            url = "postgresql://" + url[len("postgres://"):]
        db = psycopg.connect(url, row_factory=dict_row, connect_timeout=10, sslmode="require", application_name="multiagent-ai-system")
    else:
        path = Path(os.getenv("APP_DB_PATH", "./data/multiagent.db"))
        path.parent.mkdir(parents=True, exist_ok=True)
        db = sqlite3.connect(path)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys = ON")
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def init_db():
    with connect() as db:
        if _is_postgres():
            db.execute("""
                CREATE TABLE IF NOT EXISTS tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_message TEXT NOT NULL,
                    status TEXT NOT NULL,
                    result TEXT,
                    created_at TEXT NOT NULL,
                    active_agent TEXT
                )
            """)
            db.execute("ALTER TABLE tasks ADD COLUMN IF NOT EXISTS active_agent TEXT")
            db.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
                    agent TEXT NOT NULL,
                    content TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)
            db.execute("CREATE INDEX IF NOT EXISTS idx_messages_task_id ON messages(task_id)")
            db.execute("CREATE INDEX IF NOT EXISTS idx_tasks_created_at ON tasks(created_at)")
            db.execute("""CREATE TABLE IF NOT EXISTS custom_plugins (id TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL, base_url TEXT NOT NULL, auth_env TEXT, actions_json TEXT NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE, created_at TEXT NOT NULL)""")
        else:
            db.executescript("""
                CREATE TABLE IF NOT EXISTS tasks (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_message TEXT NOT NULL,
                    status TEXT NOT NULL,
                    result TEXT,
                    created_at TEXT NOT NULL,
                    active_agent TEXT
                );
                CREATE TABLE IF NOT EXISTS messages (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
                    agent TEXT NOT NULL,
                    content TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS idx_messages_task_id ON messages(task_id);
                CREATE INDEX IF NOT EXISTS idx_tasks_created_at ON tasks(created_at);
                CREATE TABLE IF NOT EXISTS custom_plugins (id TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL, base_url TEXT NOT NULL, auth_env TEXT, actions_json TEXT NOT NULL, enabled INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL);
            """)
            try:
                db.execute("ALTER TABLE tasks ADD COLUMN active_agent TEXT")
            except sqlite3.OperationalError as exc:
                if "duplicate column" not in str(exc).lower():
                    raise


def create_task(message: str) -> int:
    with connect() as db:
        statement = "INSERT INTO tasks(user_message,status,created_at) VALUES(%s,%s,%s)"
        if _is_postgres():
            cur = db.execute(statement + " RETURNING id", (message, "running", datetime.now(timezone.utc).isoformat()))
            return int(cur.fetchone()["id"])
        cur = db.execute(_sql(statement), (message, "running", datetime.now(timezone.utc).isoformat()))
        return int(cur.lastrowid)


def get_task(task_id: int):
    with connect() as db:
        row = db.execute(_sql("SELECT id,user_message,status,result,created_at,active_agent FROM tasks WHERE id=%s"), (task_id,)).fetchone()
        return dict(row) if row else None



def pause_task_for_input(task_id: int):
    with connect() as db:
        db.execute(_sql("UPDATE tasks SET status=%s,active_agent=NULL WHERE id=%s"),
                   ("needs_input", task_id))


def resume_task_with_clarification(task_id: int, response: str) -> bool:
    with connect() as db:
        cur = db.execute(_sql(
            "UPDATE tasks SET status=%s,user_message=user_message || %s,active_agent=NULL "
            "WHERE id=%s AND status=%s"
        ), ("running", "\n\nUser clarification:\n" + response, task_id, "needs_input"))
        return cur.rowcount == 1


def restart_task(task_id: int) -> bool:
    with connect() as db:
        cur = db.execute(_sql("UPDATE tasks SET status=%s,result=NULL,active_agent=NULL WHERE id=%s AND status=%s"),
                         ("running", task_id, "failed"))
        return cur.rowcount == 1


def recover_interrupted_tasks() -> int:
    with connect() as db:
        cur = db.execute(_sql(
            "UPDATE tasks SET status=%s,result=%s,active_agent=NULL WHERE status=%s"
        ), ("failed", "Task was interrupted by a server restart. Use Retry to run it again.", "running"))
        return cur.rowcount


def set_active_agents(task_id: int, agents: list[str]):
    active = ", ".join(dict.fromkeys(agents))
    with connect() as db:
        db.execute(_sql("UPDATE tasks SET active_agent=%s WHERE id=%s"), (active or None, task_id))


def set_active_agent(task_id: int, agent: str | None):
    set_active_agents(task_id, [agent] if agent else [])


def add_message(task_id: int, agent: str, content: str):
    with connect() as db:
        db.execute(_sql("INSERT INTO messages(task_id,agent,content,created_at) VALUES(%s,%s,%s,%s)"),
                   (task_id, agent, content, datetime.now(timezone.utc).isoformat()))


def finish_task(task_id: int, status: str, result: str):
    with connect() as db:
        if status == "failed":
            # Keep the last active agent so the dashboard can mark the responsible card red.
            db.execute(_sql("UPDATE tasks SET status=%s, result=%s WHERE id=%s"),
                       (status, result, task_id))
        else:
            db.execute(_sql("UPDATE tasks SET status=%s, result=%s, active_agent=NULL WHERE id=%s"),
                       (status, result, task_id))


def recent_tasks(limit: int = 30):
    with connect() as db:
        rows = db.execute(_sql("SELECT id,user_message,status,result,created_at,active_agent FROM tasks ORDER BY id DESC LIMIT %s"),
                          (limit,)).fetchall()
        return [dict(row) for row in rows]


def task_messages(task_id: int):
    with connect() as db:
        rows = db.execute(_sql("SELECT agent,content,created_at FROM messages WHERE task_id=%s ORDER BY id"),
                          (task_id,)).fetchall()
        return [dict(row) for row in rows]
