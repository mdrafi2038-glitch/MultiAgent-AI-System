"""Safe project source bundle generation and ZIP packaging."""
import io
import json
import re
import zipfile
from pathlib import PurePosixPath

MAX_FILES = 30
MAX_FILE_BYTES = 100_000
MAX_BUNDLE_BYTES = 500_000
BLOCKED_NAMES = {".env", ".env.local", ".env.production", "id_rsa", "id_ed25519", "credentials.json", "secrets.json"}


def parse_project_manifest(raw: str) -> dict:
    candidate = str(raw or "").strip()
    candidate = re.sub(r"^\s*```(?:json)?\s*", "", candidate, flags=re.IGNORECASE)
    candidate = re.sub(r"\s*```\s*$", "", candidate)
    try:
        payload = json.loads(candidate)
    except (ValueError, TypeError):
        start, end = candidate.find("{"), candidate.rfind("}")
        if start < 0 or end <= start:
            raise ValueError("The code generator did not return a JSON project manifest.")
        payload = json.loads(candidate[start:end + 1])
    if not isinstance(payload, dict) or not isinstance(payload.get("files"), list):
        raise ValueError("The project manifest must contain a files array.")
    entries = payload["files"]
    if not entries or len(entries) > MAX_FILES:
        raise ValueError(f"The project must contain between 1 and {MAX_FILES} files.")
    clean, seen, total = [], set(), 0
    for entry in entries:
        if not isinstance(entry, dict):
            raise ValueError("Every project file must be an object.")
        name, content = entry.get("path"), entry.get("content")
        if not isinstance(name, str) or not isinstance(content, str):
            raise ValueError("Every project file needs a string path and content.")
        name = name.strip()
        if not name or len(name) > 180 or "\\" in name:
            raise ValueError("A project file path is invalid.")
        path = PurePosixPath(name)
        if path.is_absolute() or not path.parts or any(part in {"", ".", ".."} for part in path.parts):
            raise ValueError("Project file paths must stay inside the project workspace.")
        if any(part.lower() in BLOCKED_NAMES or part.lower().startswith(".env.") for part in path.parts):
            raise ValueError("Credential and environment files cannot be included in project bundles.")
        if any(part.lower() == ".git" for part in path.parts):
            raise ValueError("Git internals cannot be included in project bundles.")
        normalized = path.as_posix()
        if normalized in seen:
            raise ValueError("The project contains duplicate file paths.")
        encoded = content.encode("utf-8")
        if len(encoded) > MAX_FILE_BYTES:
            raise ValueError(f"{normalized} exceeds the per-file size limit.")
        total += len(encoded)
        if total > MAX_BUNDLE_BYTES:
            raise ValueError("The generated project exceeds the 500 KB source limit.")
        seen.add(normalized)
        clean.append((normalized, content))
    return {"name": str(payload.get("name") or "Generated Project")[:100], "files": clean}


def create_project_zip(raw: str) -> tuple[bytes, dict]:
    manifest = parse_project_manifest(raw)
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path, content in manifest["files"]:
            archive.writestr(path, content)
        archive.writestr("BUILD_INFO.txt",
            "Generated by MultiAgent AI System.\n"
            "This ZIP contains project source files. It is not a compiled APK or deployed website.\n")
    data = output.getvalue()
    if len(data) > MAX_BUNDLE_BYTES * 2:
        raise ValueError("The compressed project bundle is too large.")
    return data, {"name": manifest["name"], "files": len(manifest["files"]),
                  "source_bytes": sum(len(content.encode("utf-8")) for _, content in manifest["files"])}
